# frozen_string_literal: true

require "rails_helper"

RSpec.describe ReviewSchedule do
  # Prepare the test database with coding problems
  before { seed_judge }

  # Create a test student
  let(:user) { create_user }

  # Get an existing coding problem
  let(:problem) { Problem.first }

  it "doubles the interval after a successful review" do
    # Create a review schedule for the student
    schedule = ReviewSchedule.create!(
      user: user,
      problem: problem,
      interval_days: 2,
      next_review_date: Date.current
    )

    # Simulate a successful review
    schedule.update_review!(successful: true)

    # Check that the interval increased from 2 to 4 days
    expect(schedule.interval_days).to eq(4)

    # Check that the next review is 4 days from today
    expect(schedule.next_review_date).to eq(Date.current + 4.days)
    end
    it "resets the interval after an unsuccessful review" do
      # Create a schedule without saving it to the database
      schedule = ReviewSchedule.new(
        interval_days: 8,
        next_review_date: Date.current
      )

      # Simulate an unsuccessful review
      allow(schedule).to receive(:save!).and_return(true)
      schedule.update_review!(successful: false)

      # The interval should reset from 8 days to 1 day
      expect(schedule.interval_days).to eq(1)

      # The next review should be tomorrow
      expect(schedule.next_review_date).to eq(Date.current + 1.day)
    end

  it "returns only reviews that are due" do
    # Check the SQL query generated by our due scope
    sql = ReviewSchedule.due.to_sql

    # Verify that the query filters by next_review_date
    expect(sql).to include("next_review_date")

    # Verify that the query uses <= to include overdue and today's reviews
    expect(sql).to include("<=")
  end


end